  const realFetch=global.fetch;
  global.fetch=async(url,opt)=>{
   if(!String(url).startsWith('https://raw.githubusercontent.com/'))return realFetch(url,opt);
   calls.push(String(url).split('/').pop());
   if(String(url).endsWith('stable.json'))return new Response(JSON.stringify(channel));
   return new Response(zip);
  };
  let a=await autoUpdateOnce();assert.equal(a.result,'error','no updater directories yet');assert.match(a.message,/nicht eingerichtet/);
