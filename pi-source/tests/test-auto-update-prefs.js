  assert.equal(persisted.auto,true,'auto:true must be persisted as a file');
  // Repeated page reads must not change the option.
  d=await get();assert.equal(d.auto,true);assert.equal(d.autoSettingsError,false);
  d=await get();assert.equal(d.auto,true);
  fs.writeFileSync(prefs,'invalid-json');
  d=await get();assert.equal(d.autoSettingsError,true,'invalid prefs should be flagged, not reported as deliberate off');
  // Automatische Prüfung im Pi-Server: stellt neue Versionen für den Root-Updater in die Warteschlange.
  const {autoUpdateOnce}=require('../server.js');
  const root=process.env.BMW_AI_UPDATE_ROOT,queue=path.join(root,'queue'),inbox=path.join(root,'inbox');
  fs.writeFileSync(prefs,JSON.stringify({auto:true}));
  const zip=Buffer.concat([Buffer.from('PK'),crypto.randomBytes(400)]),sha=crypto.createHash('sha256').update(zip).digest('hex');
