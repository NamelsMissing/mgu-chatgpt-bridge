  channel={schema:1,version:'0.0.1',file:'BMW_AI_Pi_Update_v0.0.1.zip',sha256:sha};
  a=await autoUpdateOnce();assert.equal(a.result,'current');
  fs.writeFileSync(prefs,JSON.stringify({auto:false}));channel={schema:1,version:'99.1.0',file:'BMW_AI_Pi_Update_v99.1.0.zip',sha256:sha};
