  const job=JSON.parse(fs.readFileSync(path.join(queue,jobs[0]),'utf8'));
  assert.equal(job.kind,'manual-github','root updater accepts the known job kind');assert.equal(job.sha256,sha);
  assert.deepEqual(fs.readFileSync(path.join(inbox,job.id+'.zip')),zip);
  a=await autoUpdateOnce();assert.equal(a.result,'waiting','no second job while one is queued');
  fs.unlinkSync(path.join(queue,jobs[0]));
  calls=[];a=await autoUpdateOnce();assert.equal(a.result,'pending','same version not re-queued within 6 h');assert.deepEqual(calls,['stable.json']);
  channel={...channel,sha256:'0'.repeat(64)};channel.version='99.0.1';channel.file='BMW_AI_Pi_Update_v99.0.1.zip';
